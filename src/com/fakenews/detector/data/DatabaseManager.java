    private synchronized void initDatabase() {
        File dataDir = new File("data");
        if (!dataDir.exists()) {
            dataDir.mkdirs();
        }

        File dbFile = new File(DB_FILE_PATH);
        if (dbFile.exists()) {
            loadFromDisk(dbFile);
        } else {
            // Seed with realistic demo baseline audits if database is brand new
            seedInitialScans();
            persistToDisk();
        }
    }

